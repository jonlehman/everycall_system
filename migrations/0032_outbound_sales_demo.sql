CREATE TABLE IF NOT EXISTS sales_prospects (
  prospect_id TEXT PRIMARY KEY,
  source_key TEXT NOT NULL UNIQUE,
  external_ref TEXT,
  business_name TEXT NOT NULL,
  owner_first_name TEXT,
  contact_name TEXT,
  contact_email TEXT,
  email_permission BOOLEAN NOT NULL DEFAULT FALSE,
  email_suppressed_at TIMESTAMPTZ,
  email_suppression_reason TEXT,
  smartlead_lead_id TEXT,
  smartlead_campaign_id TEXT,
  smartlead_status TEXT,
  last_email_event_at TIMESTAMPTZ,
  lead_delivery_email TEXT,
  phone_e164 TEXT NOT NULL,
  website_url TEXT,
  business_category TEXT,
  competitor_name TEXT,
  timezone TEXT,
  permission_granted BOOLEAN NOT NULL DEFAULT FALSE,
  permission_recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  suppressed BOOLEAN NOT NULL DEFAULT FALSE,
  suppression_reason TEXT,
  suppressed_at TIMESTAMPTZ,
  do_not_call BOOLEAN NOT NULL DEFAULT FALSE,
