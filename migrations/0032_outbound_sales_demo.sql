-- Keep this migration safe when an earlier draft already created the event table.
-- Historical rows predate durable processing and are treated as completed so a
-- deployment never replays old provider calls.
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS processing_status TEXT;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS processing_attempts INTEGER;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS processing_token TEXT;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS processing_started_at TIMESTAMPTZ;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS processed_at TIMESTAMPTZ;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS last_error_code TEXT;
ALTER TABLE sales_call_events
  ADD COLUMN IF NOT EXISTS last_error_message TEXT;

UPDATE sales_call_events
SET processing_status = 'processed',
    processing_attempts = COALESCE(processing_attempts, 0),
    processed_at = COALESCE(processed_at, created_at)
WHERE processing_status IS NULL;

ALTER TABLE sales_call_events
  ALTER COLUMN processing_status SET DEFAULT 'received',
  ALTER COLUMN processing_status SET NOT NULL,
  ALTER COLUMN processing_attempts SET DEFAULT 0,
  ALTER COLUMN processing_attempts SET NOT NULL;

